"""Multi-panel matplotlib visualization for iterative audio codec degradation history."""

from __future__ import annotations

import argparse
import os
import tempfile
from pathlib import Path
from typing import Sequence

os.environ.setdefault("MPLCONFIGDIR", tempfile.gettempdir())

import matplotlib

matplotlib.use("Agg")
import matplotlib.pyplot as plt
import numpy as np
import pandas as pd


def parse_args(argv: Sequence[str] | None = None) -> argparse.Namespace:
    """Parse command-line arguments for the degradation history plotter."""
    parser = argparse.ArgumentParser(
        description="Render a 3-panel degradation history chart from a codec benchmark CSV."
    )
    parser.add_argument(
        "--csv",
        type=Path,
        default=Path("degradation_report.csv"),
        help="Path to the input CSV file generated by codec-degradation (default: degradation_report.csv).",
    )
    parser.add_argument(
        "--out",
        type=Path,
        default=Path("degradation_history.png"),
        help="Path to save the rendered PNG figure (default: degradation_history.png).",
    )
    return parser.parse_args(argv)


def load_degradation_csv(csv_path: Path) -> pd.DataFrame:
    """Load and validate the per-iteration codec degradation CSV report."""
    if not csv_path.exists():
        raise FileNotFoundError(f"CSV report not found at '{csv_path}'")

    df = pd.read_csv(csv_path)
    required_columns = {
        "chain",
        "iteration",
        "lag_frames",
        "snr_db",
        "nsr_db",
        "nsr_linear",
        "lsd_full_db",
        "lsd_passband_db",
        "lsd_highband_db",
    }
    missing = required_columns.difference(df.columns)
    if missing:
        missing_sorted = ", ".join(sorted(missing))
        raise ValueError(f"CSV is missing required columns: {missing_sorted}")

    return df


def render_degradation_chart(df: pd.DataFrame, out_path: Path) -> None:
    """Render a 3-panel vertically stacked degradation history chart and save to PNG."""
    fig, axes = plt.subplots(
        nrows=3,
        ncols=1,
        sharex=True,
        figsize=(10, 9),
        constrained_layout=True,
    )
    ax_snr, ax_lsd, ax_lag = axes

    fig.suptitle(
        "Iterative Audio Codec Degradation History",
        fontsize=13,
        fontweight="bold",
    )

    palette = ["#1f77b4", "#d62728", "#2ca02c", "#9467bd"]

    # Panel 1: Time-Domain SNR (dB)
    for idx, (chain_name, group) in enumerate(df.groupby("chain", sort=False)):
        color = palette[idx % len(palette)]
        iterations = group["iteration"].to_numpy(dtype=float)
        snr_values = group["snr_db"].to_numpy(dtype=float)
        finite_mask = np.isfinite(snr_values)

        if np.any(finite_mask):
            ax_snr.plot(
                iterations[finite_mask],
                snr_values[finite_mask],
                marker="o",
                linewidth=2.0,
                color=color,
                label=f"{chain_name}",
            )
            if not np.all(finite_mask):
                ax_snr.plot(
                    [],
                    [],
                    linestyle="none",
                    color=color,
                    label=f"{chain_name}: non-finite iterations SNR = inf dB (bit-exact)",
                )
        else:
            ax_snr.plot(
                [],
                [],
                marker="o",
                linewidth=2.0,
                color=color,
                label=f"{chain_name}: SNR = inf dB (bit-exact)",
            )

    ax_snr.set_ylabel("SNR (dB)")
    ax_snr.set_title("Panel 1: Time-Domain Signal-to-Noise Ratio (Aligned)")
    ax_snr.grid(True, linestyle="--", alpha=0.4)
    ax_snr.legend(loc="best", frameon=True)

    # Panel 2: Spectral-Envelope Distortion (LSD dB)
    for idx, (chain_name, group) in enumerate(df.groupby("chain", sort=False)):
        color = palette[idx % len(palette)]
        iterations = group["iteration"].to_numpy(dtype=float)

        ax_lsd.plot(
            iterations,
            group["lsd_passband_db"].to_numpy(dtype=float),
            linestyle="-",
            marker="o",
            linewidth=1.8,
            color=color,
            label=f"{chain_name} | Passband (20 Hz - 16 kHz)",
        )
        ax_lsd.plot(
            iterations,
            group["lsd_highband_db"].to_numpy(dtype=float),
            linestyle="--",
            marker="s",
            linewidth=1.8,
            color=color,
            label=f"{chain_name} | Highband (16 - 20 kHz)",
        )
        ax_lsd.plot(
            iterations,
            group["lsd_full_db"].to_numpy(dtype=float),
            linestyle=":",
            linewidth=1.6,
            alpha=0.75,
            color=color,
            label=f"{chain_name} | Full band (20 Hz - 20 kHz)",
        )

    ax_lsd.set_ylabel("LSD (dB)")
    ax_lsd.set_title("Panel 2: Spectral-Envelope Distortion (Log-Spectral Distance)")
    ax_lsd.grid(True, linestyle="--", alpha=0.4)
    ax_lsd.legend(loc="best", frameon=True, fontsize=8.5, ncol=2)

    # Panel 3: Codec Framing Drift (lag_frames)
    for idx, (chain_name, group) in enumerate(df.groupby("chain", sort=False)):
        color = palette[idx % len(palette)]
        iterations = group["iteration"].to_numpy(dtype=float)
        lags = group["lag_frames"].to_numpy(dtype=float)

        ax_lag.plot(
            iterations,
            lags,
            linestyle="-",
            marker="^",
            linewidth=1.8,
            color=color,
            label=f"{chain_name}",
        )

    unique_iterations = sorted(df["iteration"].unique())
    if unique_iterations:
        ax_lag.set_xticks(unique_iterations)

    ax_lag.set_xlabel("Transcode Iteration")
    ax_lag.set_ylabel("Aligned Lag (frames)")
    ax_lag.set_title("Panel 3: Codec Framing Drift (Cross-Correlation Lag Alignment)")
    ax_lag.grid(True, linestyle="--", alpha=0.4)
    ax_lag.legend(loc="best", frameon=True)

    out_path.parent.mkdir(parents=True, exist_ok=True)
    fig.savefig(out_path, dpi=150)
    plt.close(fig)


def main(argv: Sequence[str] | None = None) -> int:
    """Entry point for CLI execution."""
    args = parse_args(argv)
    df = load_degradation_csv(args.csv)
    render_degradation_chart(df, args.out)
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
